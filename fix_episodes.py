def fix_episode(episode_num, mapping):
    base_path = f"/Users/mac/.openclaw/workspace/github-family-website/reader/episode{episode_num}"
    story_file = f"{base_path}/story.html"
    
    if not os.path.exists(story_file):
        print(f"Episode {episode_num}: story.html not found")
        return
    
    with open(story_file, 'r', encoding='utf-8') as f:
        content = f.read()
    
    replaced = 0
    for scene_text, img_file in mapping.items():
        old_html = f'<div class="placeholder">📷 {scene_text}</div>'
        new_html = f'<img src="images/{img_file}" alt="{scene_text}">'
        if old_html in content:
            content = content.replace(old_html, new_html)
            replaced += 1
            print(f"Episode {episode_num}: Replaced '{scene_text}' -> '{img_file}'")
        else:
            print(f"Episode {episode_num}: NOT FOUND '{scene_text}'")
    
    with open(story_file, 'w', encoding='utf-8') as f:
        f.write(content)
    
    print(f"Episode {episode_num}: Total replaced: {replaced}/{len(mapping)}")

